"""Phase 1 tuning loop, on the dev cuts and the null cuts only.

Runs each v2 agent in memory (nothing is written to the ledger) with candidate values of
the allowed knobs: kri_monitor alpha, csm z_threshold and sd_ratio_max, qtl_detector
approach_band. Scores the drafts with the eval harness's matching rules and writes
docs/tuning-phase1.md. The holdout and sweep cuts are not read here.

Decision rule, fixed before looking at the numbers: keep the default of a knob unless
the default breaks an exit criterion on these cuts (at most 1 false positive on DC-BASE,
mean at most 1 per null cut, nothing lost on DC-RBQM-CORE); then take the candidate
closest to the default that meets them.

    uv run python scripts/tune_phase1.py [--out PATH]
"""

import argparse
import uuid
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import structlog

from meridian.agents.base import Agent, AgentConfig, AgentContext, FindingDraft
from meridian.domain.dedup import STUDY_SCOPE, parse_dedup_key
from meridian.domain.enums import Visibility
from meridian.domain.events import DataCut, Event
from meridian.evals.matching import FindingRecord, match_faults
from meridian.faults.inject import GroundTruth
from meridian.platform.clock import FixedClock
from meridian.platform.config import Settings
from meridian.platform.container import Container

NOW = datetime(2026, 11, 7, tzinfo=UTC)
BASE, DEV = "DC-BASE", "DC-RBQM-CORE"
NULLS = tuple(f"DC-NULL-S{i}" for i in range(1, 6))
GRIDS: dict[str, list[dict[str, float]]] = {
    "rbqm.kri_monitor": [{"alpha": a} for a in (0.01, 0.005, 0.001, 0.0001, 0.00001)],
    "rbqm.csm": [
        {"z_threshold": z, "sd_ratio_max": r} for z in (3.0, 3.5, 4.0) for r in (0.5, 0.6, 0.7)
    ],
    "rbqm.qtl_detector": [{"approach_band": b} for b in (0.01, 0.02, 0.03)],
}


def _trigger(cut: str) -> Event:
    return Event(
        seq=1,
        event_id=uuid.uuid7(),
        occurred_at=NOW,
        recorded_at=NOW,
        actor="tune",
        visibility=Visibility.BLINDED,
        payload=DataCut(cut_id=cut, study_id="MRD-201", path=cut),
        prev_hash="0" * 64,
        hash="1" * 64,
    )


def _records(drafts: Sequence[FindingDraft], agent: Agent[Any], cut: str) -> list[FindingRecord]:
    return [
        FindingRecord(
            seq=i,
            finding_id=f"{cut}#{i}",
            agent_id=agent.agent_id,
            agent_version=agent.version,
            kind=d.kind,
            site=d.site_id or STUDY_SCOPE,
            cut_id=cut,
            check=parse_dedup_key(d.dedup_key).check,
            severity=d.severity.value,
            score=d.score,
            title=d.title,
        )
        for i, d in enumerate(drafts)
    ]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("docs/tuning-phase1.md"))
    args = parser.parse_args()
    settings = Settings()
    structlog.configure(wrapper_class=structlog.make_filtering_bound_logger(20))  # info and up
    log = structlog.get_logger()
    lines = [
        "# Phase 1 tuning (dev and null cuts only)",
        "",
        "Generated by `scripts/tune_phase1.py`. Agents run in memory; nothing here is in the",
        "ledger. Cuts: DC-BASE and DC-NULL-S1 to S5 (every finding is a false positive) and",
        "DC-RBQM-CORE (6 planted faults). The holdout and the sweep were not generated yet.",
        "",
        "Decision rule, fixed before the numbers: keep a knob's default unless it breaks an",
        "exit criterion on these cuts (DC-BASE FP <= 1, mean null FP <= 1, no planted fault",
        "lost on DC-RBQM-CORE); then take the candidate closest to the default that meets them.",
        "",
    ]
    with Container.build(settings) as c:
        faults = list(GroundTruth.load(settings.ground_truth_dir / f"{DEV}.json").faults)
        readers = {cut: c.study_reader(cut) for cut in (BASE, DEV, *NULLS)}
        registry = c.agent_registry()
        for agent_id, grid in GRIDS.items():
            registered = registry.get(agent_id)
            agent, default = registered.agent, registered.config
            lines += [
                f"## {agent_id}",
                "",
                "| Candidate | DC-BASE FP | Null FP (S1..S5) | Mean null FP "
                "| CORE detected (own faults) | CORE FP |",
                "| --- | ---: | --- | ---: | --- | ---: |",
            ]
            for overrides in grid:
                config: AgentConfig = default.model_copy(update=overrides)
                results: dict[str, list[FindingRecord]] = {}
                for cut, reader in readers.items():
                    ctx = AgentContext(study=reader, clock=FixedClock(NOW), config=config, log=log)
                    results[cut] = _records(agent.run(_trigger(cut), ctx), agent, cut)
                own = [f for f in faults if _owner(f.expected_kind.value) == agent_id]
                matched = match_faults(own, results[DEV])
                detected = [m.fault_id for m in matched.matches if m.detected]
                null_fp = [len(results[n]) for n in NULLS]
                is_default = all(getattr(default, k) == v for k, v in overrides.items())
                label = ", ".join(f"{k} {v:g}" for k, v in overrides.items())
                lines.append(
                    f"| {label}{' (default)' if is_default else ''} | {len(results[BASE])} | "
                    f"{', '.join(map(str, null_fp))} | {sum(null_fp) / len(null_fp):.1f} | "
                    f"{len(detected)} of {len(own)} ({', '.join(detected) or 'none'}) | "
                    f"{len(matched.false_positives)} |"
                )
            lines.append("")
            if agent_id == "rbqm.kri_monitor":
                lines += ["False positives by check on the null cuts, at the default alpha:", ""]
                for cut in (BASE, *NULLS):
                    ctx = AgentContext(
                        study=readers[cut], clock=FixedClock(NOW), config=default, log=log
                    )
                    found = [
                        f"{d.site_id} {parse_dedup_key(d.dedup_key).check} (score {d.score:.2f})"
                        for d in agent.run(_trigger(cut), ctx)
                    ]
                    lines.append(f"* {cut}: {', '.join(found) or 'none'}")
                lines.append("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


def _owner(kind: str) -> str:
    return {"site_data_anomaly": "rbqm.csm", "qtl_breach": "rbqm.qtl_detector"}.get(
        kind, "rbqm.kri_monitor"
    )


if __name__ == "__main__":
    main()
